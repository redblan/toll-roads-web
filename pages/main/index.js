export class MainPage {
    constructor(parent) {
        this.parent = parent;
    }

    get pageRoot() {
        return document.getElementById('main-page');
    }

    getHTML() {
        return `
            <div id="main-page">
                <div class="main-hero">
                    <div class="container">
                        <h1>🛣 Платные дороги России</h1>
                        <p>Государственная компания «Автодор» управляет скоростными
                           автомагистралями федерального значения. Выберите маршрут,
                           чтобы узнать подробности и рассчитать стоимость проезда.</p>
                    </div>
                </div>
                <div class="container">
                    <div class="section-title">Маршруты</div>
                    <div class="row g-4" id="routes-grid"></div>
                    <p class="footer-note">© Баринов Егор Сергеевич, ИУ5-41Б — Лабораторная работа 3</p>
                </div>
            </div>
        `;
    }

    clickCard(routeId) {
        const route = ROUTES_DATA.find(r => r.id === routeId);
        const productPage = new ProductPage(this.parent, route);
        productPage.render();
    }

    render() {
        this.parent.innerHTML = '';
        this.parent.insertAdjacentHTML('beforeend', this.getHTML());

        const grid = document.getElementById('routes-grid');
        ROUTES_DATA.forEach(route => {
            const card = new RouteCardComponent(grid);
            card.render(route, () => this.clickCard(route.id));
        });
    }
}